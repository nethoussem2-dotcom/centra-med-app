def t(key, page: ft.Page):
    """Get translated string based on client storage language"""
    # default to Arabic if not set
    lang = page.client_storage.get("language") or "ar"
    return translations.get(lang, translations['ar']).get(key, key)

def is_rtl(page: ft.Page):
    """Returns True if current language is right-to-left"""
    lang = page.client_storage.get("language") or "ar"
    return lang == "ar"
